"""The Burrowers (1933 scenario): the Hive has no ships. Once it knows the Burrowers tech (95180) and holds a
shore, it tunnels under the strait. The far side is warned, and two waves of Hive troops break out of the ground
on the other side, 60 and 150 days later, as long as the Hive still holds the near shore.

Event ids per crossing c:  9580000 + 10c      the digging starts (UA0)
                           9580000 + 10c + 1  first wave       + 2  second wave (UA0)
                           9580000 + 10c + 3+ tremors under the strait (one per possible defender)

DH supplies land units overland or by convoy, and the Hive has neither across a strait: troops that break out
on the far side fight out of supply unless they take enough land to stand on. Two waves, so the bridgehead
has a chance to grow before the first wave starves.
"""
C = "UA0"
DEATH = (29, "december", 1963)
TECH = 95180
ID0 = 9580000
WAVES = [(60, 3), (150, 3)]             # (days after the digging starts, Hybrid divisions)
# The defender's answer: a locked coastal militia at the landing site (10 money, 100 supplies). Only scenario
# units can be locked, so each is a dormant division in its country's scenario file, woken by the warning.
# Only the Soviet file is generated by the mod so far; other countries need their scenario files.
MILITIA_COST = (10, 100)                 # money, supplies
DORMANT = {  # (crossing index, tag): (unit id type, id, militia model) - models from each country's 1933 file
    (0, "USA"): (19501, 901, 3),         # Nome, Bering Strait (the 1933 US army has no militia; 3 is the era's model)
    (1, "SOV"): (19501, 900, 4),         # Okha, Tatar Strait
    (1, "JAP"): (19501, 902, 4),         # Okha, if Japan has taken northern Sakhalin
    (2, "JAP"): (19501, 903, 4),         # Sapporo, La Perouse Strait
    (3, "JAP"): (19501, 904, 4),         # Nagasaki, Tsushima Strait
    (4, "ENG"): (19501, 905, 3),         # Dover, the Channel
    (5, "SPR"): (19501, 906, 3),         # Tangier, Strait of Gibraltar (Spanish in 1933)
}
# vanilla DH Full 1933 country files copied to src/inc1933 and patched with the dormant units above
# (the Soviet file is patched separately, by story.soviet_inc)
PATCHED_INC = {"USA": "usa.inc", "JAP": "japan.inc", "ENG": "united kingdom.inc", "SPR": "spain.inc"}

def dormant_units(tag):
    out = ""
    for (c, t), (typ, uid, model) in DORMANT.items():
        if t == tag:
            far = CROSSINGS[c][2]
            out += (f'landdivision = {{ dormant = yes id = {{ type = {typ} id = {uid} }} '
                    f'name = "Coastal Militia of {CROSSINGS[c][0][4:].title()}" type = militia model = {model} locked = yes }}\n')
    return out

def warn_options(c, t, far):
    opts = []
    if (c, t) in DORMANT:
        typ, uid, _ = DORMANT[(c, t)]
        money, supplies = MILITIA_COST
        opts.append(("Raise a coastal militia", 80, [f"type = money value = -{money}", f"type = supplies value = -{supplies}",
                     f"type = activate_division which = {typ} value = {uid} where = {far} when = 0"]))
    opts.append(("Nothing can dig that far", 20, []))
    return opts
COST = 40                                # manpower spent on each crossing (the swarm sent through the tunnel)

# (name, near shore, far shore, who may hold the far shore)
CROSSINGS = [
    ("the Bering Strait", 1182, 2145, "USA"),            # Anadyr -> Nome
    ("the Tatar Strait", 1189, 1541, "SOV UA2 JAP"),     # Nikolayevsk-on-Amur -> Okha (Sakhalin)
    ("the La Perouse Strait", 1542, 1545, "JAP"),        # Toyohara -> Sapporo
    ("the Tsushima Strait", 1232, 1560, "JAP"),          # Busan -> Nagasaki
    ("the Channel", 49, 26, "ENG"),                      # Calais -> Dover
    ("the Strait of Gibraltar", 348, 715, "SPR SPA FRA ENG"),   # Gibraltar -> Tangier
]

def ctl(p, tag=C): return f"control = {{ province = {p} data = {tag} }}"

def events(g):
    import breakout
    E = ["#########################################################################",
         "#  RESISTANCE MOD - The Burrowers: the Hive tunnels under the straits (9580000+)",
         "#########################################################################", ""]
    best = [("technology = 95060", 20), ("technology = 95040 NOT = { technology = 95060 }", 19),
            ("NOT = { technology = 95040 }", 18)]
    for c, (name, near, far, holders) in enumerate(CROSSINGS):
        base = ID0 + 10 * c
        tags = holders.split()
        far_nm, near_nm = breakout.g_name(far), breakout.g_name(near)
        held_by_enemy = "OR = { " + " ".join(ctl(far, t) for t in tags) + " }"
        dig = [f"type = manpowerpool value = -{COST}"]
        # the Hive does no diplomacy: whoever holds the far shore is now at war with it
        dig += [f"trigger = {{ {ctl(far, t)} NOT = {{ war = {{ country = {t} country = {C} }} }} }} type = war which = {t}"
                for t in tags]
        dig += [f"trigger = {{ {ctl(far, t)} }} type = event which = {base + 3 + i} where = {t} when = 1"
                for i, t in enumerate(tags)]
        dig += [f"type = event which = {base + 1 + k} where = {C} when = {days}" for k, (days, _) in enumerate(WAVES)]
        E += g.event(base, f"Burrowing under {name}",
            f"The Burrowers have reached the shore at {near_nm}. They are already boring down beneath the seabed "
            f"towards {far_nm}. In a few weeks the swarm will come up behind the humans' coastal guns.",
            [("Dig", dig)], country=C,
            trigger=[f"technology = {TECH}", ctl(near), f"NOT = {{ {ctl(far)} }}", held_by_enemy],
            date=(1, "january", 1940), offset=30, deathdate=DEATH, text_id=f"RES_BURROW_{c}")
        for k, (days, size) in enumerate(WAVES):
            # the tunnel only works while the Hive still holds the near shore
            army = [f'trigger = {{ {ctl(near)} }} type = add_corps which = "Burrow Brood of {far_nm} {"I" * (k + 1)}" '
                    f'value = land where = {far}']
            for d in range(size):
                army += [f'trigger = {{ {ctl(near)} {tc} }} type = add_division which = '
                         f'"{["I", "II", "III", "IV"][d]} {far_nm} Burrowers{" " + "I" * (k + 1) if k else ""}" value = infantry when = {m}'
                         for tc, m in best]
            E += g.event(base + 1 + k, f"The Swarm Surfaces at {far_nm}",
                f"The ground at {far_nm} has split open. Hybrids are pouring out of the tunnel mouth.",
                [("Overrun them", army)], country=C, text_id=f"RES_BURROW_WAVE_{c}")
        for i, t in enumerate(tags):
            E += g.event(base + 3 + i, f"Tremors under {name}",
                f"Seismographs and listening posts at {far_nm} report something boring through the rock beneath "
                f"{name}, coming from {near_nm}. Whatever it is, it will come up on our side of the water.",
                warn_options(c, t, far),
                country=t, text_id=f"RES_BURROW_WARN_{c}_{t}")
    assert ID0 + 10 * len(CROSSINGS) < 9590000
    return E
